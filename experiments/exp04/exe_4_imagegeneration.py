import gradio as gr

import zipfile
import os

styles = {
    "Realistic": "realistic, ultra detailed, 8k",
    "Anime": "anime style, vibrant colors",
    "Oil Painting": "oil painting, masterpiece",
    "Watercolor": "watercolor painting",
    "Pixel Art": "pixel art"
}

def generate_images(prompt, style, negative_prompt, num_images):

    final_prompt = prompt + ", " + styles[style]

    images = pipe(
        prompt=final_prompt,
        negative_prompt=negative_prompt,
        num_images_per_prompt=int(num_images)
    ).images

    # Save generated images
    image_files = []

    for i, img in enumerate(images):
        filename = f"generated_image_{i+1}.png"
        img.save(filename)
        image_files.append(filename)

    # Create ZIP file
    zip_filename = "generated_images.zip"

    with zipfile.ZipFile(zip_filename, "w") as zipf:
        for file in image_files:
            zipf.write(file)

    return images, zip_filename

with gr.Blocks(theme=gr.themes.Soft()) as demo:

    gr.Markdown("# AI Image Generator")

    with gr.Row():

        with gr.Column():

            prompt = gr.Textbox(label="Prompt")

            style = gr.Dropdown(
                choices=["Realistic","Anime","Oil Painting","Watercolor","Pixel Art"]
            )

            negative_prompt = gr.Textbox(label="Negative Prompt")

            num_images = gr.Slider(1,4,value=1)

            generate_btn = gr.Button("Generate Images")

        with gr.Column():

            gallery = gr.Gallery()

            download = gr.File()

    #  THIS MUST BE INSIDE THE BLOCK
    generate_btn.click(
        fn=generate_images,
        inputs=[
            prompt,
            style,
            negative_prompt,
            num_images
        ],
        outputs=[
            gallery,
            download
        ]
    )

demo.launch()